source_dir=pathlib.Path(__file__).resolve().parent
default_cache=next((p/'inputs/flyff-source' for p in source_dir.parents if (p/'inputs/flyff-source').is_dir()),pathlib.Path.home()/'.cache/flyff-mu-laboratorio/source')
CACHE = pathlib.Path(os.environ.get('FLYFF_SOURCE_CACHE',str(default_cache)))
TREE = json.loads(gzip.decompress(pathlib.Path(__file__).with_name('arbol-origen.json.gz').read_bytes()))
REV = TREE['sha']
ENTRIES = {e['path'].lower(): e for e in TREE['tree'] if e['type'] == 'blob'}

def fetch(path):
    entry = ENTRIES.get(path.lower())
    if entry is None:
        raise FileNotFoundError(path)
    dest = CACHE / entry['path']
    def valid(data):
        return hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest() == entry['sha']
    if dest.exists() and valid(dest.read_bytes()):
        return dest
    url = 'https://raw.githubusercontent.com/ed3ath/flyff-web-mmo/' + REV + '/' + urllib.parse.quote(entry['path'])
    for retry in range(4):
        try:
            data = urllib.request.urlopen(url, timeout=60).read()
            if not valid(data):
                raise ValueError('Git blob identity mismatch: '+path)
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
            return dest
        except Exception:
            if retry == 3: raise
            time.sleep(retry + 1)

def batch(paths):
    paths = sorted(set(paths))
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as pool:
        result = list(pool.map(fetch, paths))
    print('FETCHED',len(result), 'files',sum(p.stat().st_size for p in result),'bytes',flush=True)
    return result

