export function getItemVisualSpec(item: MuItem): {
  labelColor: string;
  glowColor: string;
} {
  if (item.rarity === 'ancient') {
    return { labelColor: '#38bdf8', glowColor: '#0284c7' };
  }
  if (item.rarity === 'excellent') {
    return { labelColor: '#4ade80', glowColor: '#16a34a' };
  }
  if (item.enhanceLevel >= 11) {
    return { labelColor: '#fbbf24', glowColor: '#d97706' };
  }
  if (item.enhanceLevel >= 7) {
    return { labelColor: '#f8fafc', glowColor: '#64748b' };
  }
  return { labelColor: '#cbd5e1', glowColor: '#475569' };
}
